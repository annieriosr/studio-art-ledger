/* Cosas bills — minimal offline shell for Annie's sale invoices */
const CACHE = "cosas-bills-v1";
const PRECACHE = [
  "./",
  "./index.html",
  "./factura-venta.html",
  "./manifest.webmanifest",
  "./icon-180.png",
  "./icon-192.png",
  "./icon-512.png"
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k)))
    ).then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  // Only handle this fair folder (scope is ./ when registered from here)
  if (!url.pathname.includes("/fairs/casas-ecuador-2026/")) return;

  event.respondWith(
    caches.match(req).then((cached) => {
      const network = fetch(req)
        .then((res) => {
          if (res && res.ok && (req.destination === "document" || req.destination === "image" || req.url.endsWith(".webmanifest") || req.url.endsWith(".js") || req.url.endsWith(".html") || req.url.endsWith(".png"))) {
            const copy = res.clone();
            caches.open(CACHE).then((cache) => cache.put(req, copy));
          }
          return res;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
